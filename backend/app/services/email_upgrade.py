"""AI coverage for every customer: upgrade a finished run's template emails to fact-checked LLM drafts in the background.

The run itself stays fast (the most severe customers are written by the LLM inside it). Afterwards a worker job walks the
remaining template emails in severity order, a few batches at a time, and stops when everything is covered, the call
budget is spent, or the LLM is unavailable. Each draft passes the same fact check as any other email, emails that a person
has approved, edited or regenerated in the meantime are never touched, and an email that keeps failing the check simply
stays a template.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from math import ceil

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.core.config import Settings
from app.core.logging import get_logger
from app.db.models import AuditLog, Communication, Run
from app.llm.outputs import EmailBatchOut
from app.llm.service import LLMCallError, LLMService, LLMUnavailable
from app.services.comm_ops import facts_of, tone_guide_text
from app.services.comms import render
from app.services.qa import check_email
from app.services.tone import ToneItem, review_tone

log = get_logger(__name__)

ACTOR = "ai_upgrade"
FAILED = "failed"  # marker stored in a communication's qa: the LLM could not produce a checked draft, leave the template


def _candidates():
    return (
        select(Communication)
        .where(
            Communication.generator == "template",
            Communication.status.in_(("draft", "qa_failed")),
            Communication.qa["ai_upgrade"].astext.is_(None),
        )
        .order_by(Communication.max_severity.desc(), Communication.customer_unique_id)
    )


async def upgrade_batch(
    session: AsyncSession, llm: LLMService, settings: Settings, run_id: str, batch: list[Communication]
) -> tuple[int, int, int, Exception | None]:
    """Upgrade one batch. Returns (llm_calls, upgraded, failed, error). `error` is set when the LLM became unavailable;
    the emails it left unfinished are not marked as failed, so a later pass retries them."""
    guide = tone_guide_text(settings.kb_dir)
    pairs = {}
    for c in batch:
        facts, allow = facts_of(c)
        pairs[facts.customer_ref] = (c, facts, allow)
    versions = {c.id: c.version for c in batch}
    accepted: dict = {}
    feedback: dict[str, list[str]] = {}
    pending = list(pairs)
    calls = 0
    error: Exception | None = None
    for _ in range(2):  # the first draft and one redraft with the checker's reasons
        if not pending:
            break
        fb = "\n".join(f"- customer_ref {r}: " + "; ".join(feedback[r]) for r in pending if feedback.get(r))
        try:
            res = await llm.generate(
                agent="customer_success", role="email", prompt="email",
                context={
                    "locale": pairs[pending[0]][1].locale, "tone_guide": guide, "feedback": fb,
                    "facts_json": json.dumps([pairs[r][1].model_dump() for r in pending], ensure_ascii=False, indent=1),
                },
                schema=EmailBatchOut, run_id=run_id, max_output_tokens=16384,
            )
        except (LLMUnavailable, LLMCallError) as e:
            error = e
            break
        calls += 1
        returned: set[str] = set()
        for out in res.parsed.emails:
            ref = out.customer_ref.strip()
            if ref not in pending or ref in returned:
                continue
            returned.add(ref)
            _, facts, allow = pairs[ref]
            report = check_email(out.subject.strip(), out.body.strip(), facts, allow)
            if report.passed:
                accepted[ref] = (out, res, report)
            else:
                feedback[ref] = report.failures()
        for ref in pending:
            if ref not in accepted and ref not in feedback:
                feedback[ref] = ["The model returned no email for this customer."]
        pending = [r for r in pending if r not in accepted]

    verdicts: dict = {}
    if accepted and settings.tone_review_enabled and llm.available:
        items = [ToneItem(ref, pairs[ref][1].locale, o.subject.strip(), o.body.strip()) for ref, (o, _, _) in accepted.items()]
        verdicts = await review_tone(llm, items, guide=guide, batch_size=settings.tone_batch_size, run_id=run_id)
        calls += ceil(len(items) / settings.tone_batch_size)

    upgraded = failed = 0
    for ref, (out, res, report) in accepted.items():
        c, _, allow = pairs[ref]
        await session.refresh(c)
        if c.generator != "template" or c.status not in ("draft", "qa_failed") or c.version != versions[c.id]:
            continue  # approved, edited or regenerated by a person in the meantime: leave it alone
        before = {"subject": c.subject, "body": c.body, "version": c.version, "generator": c.generator}
        c.subject, c.body = render(out.subject.strip(), allow), render(out.body.strip(), allow)
        c.generator, c.model, c.prompt_version = "llm", res.model, res.prompt_version
        qa = {**report.model_dump(), "generator": "llm"}
        if (v := verdicts.get(ref)) is not None:
            qa["tone"] = {**v.as_dict(), "rewritten": False}
        c.qa, c.status = qa, "draft"
        c.version += 1
        c.attempts += 1
        session.add(AuditLog(actor=ACTOR, action="communication.ai_upgrade", entity="communication", entity_id=c.id,
                             detail={"before": before}))
        upgraded += 1
    if error is None:
        for ref in pending:  # still failing the check after the redraft: keep the template, do not try again
            c = pairs[ref][0]
            await session.refresh(c)
            if c.generator == "template" and c.version == versions[c.id]:
                c.qa = {**c.qa, "ai_upgrade": FAILED}
                failed += 1
    await session.commit()
    return calls, upgraded, failed, error


async def upgrade_chunk(
    session_factory: async_sessionmaker[AsyncSession], llm: LLMService, settings: Settings, run_id: str, *, reset: bool = False
) -> dict:
    """Run a few batches and record progress in the run's metrics. The returned `state` is `running` when more is left
    to do (the caller schedules the next chunk), `done` when every email is covered, or `stopped` with a reason."""
    async with session_factory() as s:
        run = await s.get(Run, run_id)
        if run is None or run.status != "succeeded":
            return {"state": "skipped"}
        progress = {"upgraded": 0, "failed": 0, "calls": 0, **((run.metrics or {}).get("ai_upgrade") or {})}
        if reset:
            progress.update(calls=0, failed=0)
            marked = (
                await s.execute(select(Communication).where(Communication.run_id == run_id, Communication.qa["ai_upgrade"].astext.isnot(None)))
            ).scalars().all()
            for c in marked:
                c.qa = {k: v for k, v in c.qa.items() if k != "ai_upgrade"}
            await s.commit()

    stop_reason: str | None = None
    async with session_factory() as s:
        for _ in range(settings.email_upgrade_chunk_batches):
            if progress["calls"] >= settings.email_upgrade_max_calls:
                stop_reason = f"call budget of {settings.email_upgrade_max_calls} reached"
                break
            if not llm.available:
                stop_reason = llm.breaker_reason or "the LLM is unavailable"
                break
            batch = (
                await s.execute(_candidates().where(Communication.run_id == run_id).limit(settings.email_batch_size))
            ).scalars().all()
            if not batch:
                break
            calls, upgraded, failed, error = await upgrade_batch(s, llm, settings, run_id, list(batch))
            progress["calls"] += calls
            progress["upgraded"] += upgraded
            progress["failed"] += failed
            if error is not None:
                stop_reason = str(error)[:200]
                break
        remaining = (
            await s.execute(select(func.count()).select_from(_candidates().where(Communication.run_id == run_id).subquery()))
        ).scalar_one()

    state = "stopped" if stop_reason and remaining else ("running" if remaining else "done")
    progress.update(state=state, remaining=remaining, reason=stop_reason if state == "stopped" else None,
                    updated_at=datetime.now(timezone.utc).isoformat())
    async with session_factory() as s:
        run = await s.get(Run, run_id)
        if run is not None:
            run.metrics = {**(run.metrics or {}), "ai_upgrade": progress}
            await s.commit()
    log.info("email_upgrade_chunk", run_id=run_id, **{k: v for k, v in progress.items() if k != "updated_at"})
    return progress
